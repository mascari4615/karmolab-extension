import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';
const root = fileURLToPath(new URL('../', import.meta.url));
export const arcaFiles = ['block-defaults.js', 'block-toast.js', 'block-core.js', 'arca-profile.js', 'arca-auto-block.js', 'arca-insight.js', 'arca-block.js', 'arca-seen.js', 'arca-scrap.js', 'arca-liked-link.js'];
const files = ['features/keyword-core.js', ...arcaFiles.map(file => 'features/arca/' + file)];
const contents = (await Promise.all(files.map(file => readFile(path.join(root, file), 'utf8')))).join('\n;\n');
await writeFile(path.join(root, 'features/arca/entry.js'), `/* GENERATED by scripts/build-arca-entry.mjs. Edit features/arca sources. */
(async () => {
const nativeChrome = globalThis.chrome;
if (!(await nativeChrome.runtime.sendMessage({ type: 'arca.canRun' }))?.ok) return;
if (document.documentElement.dataset.karmoArcaOwner) return;
document.documentElement.dataset.karmoArcaOwner = nativeChrome.runtime.id;
${contents}
})().catch(console.error);
`);
